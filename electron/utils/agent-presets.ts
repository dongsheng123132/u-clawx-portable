export function localizePresetAgent(preset: PresetAgentTemplate, locale?: string | null): LocalizedPresetAgent {
  const resolvedLocale = resolvePresetLocale(locale);
  const localized = preset.locales[resolvedLocale];
  return {
    id: preset.id,
    name: localized.name,
    description: localized.description,
    icon: preset.icon,
    category: preset.category,
    categoryLabel: CATEGORY_LABELS[preset.category][resolvedLocale],
    systemPrompt: localized.systemPrompt,
    skillIds: [...preset.skillIds],
  };
}

export function inferPresetLocaleFromName(
  preset: PresetAgentTemplate,
  name?: string | null,
): PresetAgentLocale | undefined {
  const normalizedName = name?.trim();
  if (!normalizedName) return undefined;
  return PRESET_AGENT_LOCALES.find((locale) => preset.locales[locale].name === normalizedName);
}

export function findPresetAgent(presetId: string): PresetAgentTemplate | null {
  const normalizedId = presetId.trim();
  return PRESET_AGENTS.find((preset) => preset.id === normalizedId) ?? null;
}
